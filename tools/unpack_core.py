#!/usr/bin/env python3
"""Unpack CORE.GT4 (the main executable) from the user's own disc image.

Usage: python tools/unpack_core.py path/to/your.iso [OUT_DIR]   (default: extracted/)

Writes, locally only (extracted/ is git-ignored):
  core.bin  flat memory image from 0x00100000 to the end of the last record
  core.elf  the same records wrapped in a minimal ELF for splat / Ghidra

core.elf is generated by this script, not taken from the disc. Every address
and field it uses, and how each one was confirmed, is in docs/analysis/CORE_FORMAT.md.
Values below are for NTSC-U SCUS-97328 v2.00 only.
"""
import struct
import sys
import zlib
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from iso9660 import Iso  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent

MAGIC = 0x176265B3      # header word at 0x100 (observed on one disc)
FIRST_RECORD = 0x12C    # records of {u32 vaddr, u32 size, data} run to end of file
END_ADDR = 0x008A215C   # confirmed: crt0 clears bss up to here, SetupHeap(_end)
EE_FLAGS = 0x20924001   # copied from the disc's own boot ELF header
PF_X, PF_W, PF_R = 1, 2, 4


def unpack(raw: bytes) -> bytes:
    if raw[:2] != b"\x01\x01":
        raise ValueError(f"unknown CORE.GT4 tag {raw[:2].hex()}")
    size = struct.unpack_from("<I", raw, 2)[0]
    d = zlib.decompressobj(-15)
    out = d.decompress(raw[6:]) + d.flush()
    if len(out) != size:
        raise ValueError(f"size mismatch: {len(out)} != {size}")
    return out


def records(data: bytes):
    """Yield (vaddr, bytes) for each load record. Must end exactly at EOF."""
    off = FIRST_RECORD
    while off < len(data):
        vaddr, size = struct.unpack_from("<II", data, off)
        off += 8
        if off + size > len(data):
            raise ValueError(f"record at {off - 8:#x} runs past end of file")
        yield vaddr, data[off:off + size]
        off += size


SHT_PROGBITS, SHT_NOBITS, SHT_STRTAB = 1, 8, 3
SHF_WRITE, SHF_ALLOC, SHF_EXECINSTR = 1, 2, 4


def make_elf(segs, entry: int) -> bytes:
    """segs: list of (vaddr, bytes, memsz, flags).

    Sections only mirror the segments (.text = record 1, .data = record 2,
    .bss = the rest of the data segment's memsz) so tools like splat can read
    the file. Finer boundaries (rodata, sdata, ...) are not known yet.
    """
    ehsize, phsize, shsize = 52, 32, 40
    # File offsets follow vaddr (offset = 0x1000 + vaddr - base), so objcopy
    # -O binary, core.bin and splat's rom offsets all agree.
    base = segs[0][0]
    body, phs, placed = bytearray(), b"", []
    for vaddr, blob, memsz, flags in segs:
        offset = 0x1000 + vaddr - base
        phs += struct.pack("<8I", 1, offset, vaddr, vaddr, len(blob), memsz, flags, 0x10)
        placed.append((vaddr, offset, blob, memsz, flags))
        body.extend(b"\0" * (offset - 0x1000 - len(body)))
        body.extend(blob)
    offset = 0x1000 + len(body)
    offset += (-offset) % 0x10

    shstr = b"\0.text\0.data\0.bss\0.shstrtab\0"
    name = {n: shstr.index(n.encode()) for n in (".text", ".data", ".bss", ".shstrtab")}
    shstr_off = offset
    sh_off = shstr_off + len(shstr) + (-len(shstr)) % 4
    (t_va, t_off, t_blob, _, _), (d_va, d_off, d_blob, d_memsz, _) = placed
    bss_va = (d_va + len(d_blob) + 0xF) & ~0xF
    shs = b"\0" * shsize
    shs += struct.pack("<10I", name[".text"], SHT_PROGBITS, SHF_ALLOC | SHF_EXECINSTR,
                       t_va, t_off, len(t_blob), 0, 0, 0x10, 0)
    shs += struct.pack("<10I", name[".data"], SHT_PROGBITS, SHF_ALLOC | SHF_WRITE,
                       d_va, d_off, len(d_blob), 0, 0, 0x10, 0)
    shs += struct.pack("<10I", name[".bss"], SHT_NOBITS, SHF_ALLOC | SHF_WRITE,
                       bss_va, shstr_off, d_va + d_memsz - bss_va, 0, 0, 0x10, 0)
    shs += struct.pack("<10I", name[".shstrtab"], SHT_STRTAB, 0,
                       0, shstr_off, len(shstr), 0, 0, 1, 0)

    eh = struct.pack(
        "<4sBBBB8sHHIIIIIHHHHHH",
        b"\x7fELF", 1, 1, 1, 0, b"\0" * 8,
        2, 8, 1,               # ET_EXEC, EM_MIPS, EV_CURRENT
        entry, ehsize, sh_off,
        EE_FLAGS,
        ehsize, phsize, len(segs), shsize, 5, 4,
    )
    tail = shstr.ljust(sh_off - shstr_off, b"\0") + shs
    return (eh + phs).ljust(0x1000, b"\0") + bytes(body).ljust(shstr_off - 0x1000, b"\0") + tail


def main() -> int:
    if len(sys.argv) not in (2, 3):
        print(__doc__)
        return 2
    out_dir = Path(sys.argv[2]) if len(sys.argv) == 3 else ROOT / "extracted"
    iso = Iso(sys.argv[1])
    e = iso.lookup("CORE.GT4")
    data = unpack(iso.read(e.lba, e.size))

    magic, _, entry = struct.unpack_from("<III", data, 0x100)
    if magic != MAGIC:
        raise ValueError(f"unsupported CORE.GT4 (magic {magic:#x})")
    recs = sorted(records(data))
    if len(recs) != 2:
        raise ValueError(f"expected 2 records (text, data), got {len(recs)}")
    (text_va, text), (data_va, dat) = recs

    base, end = text_va, data_va + len(dat)
    flat = bytearray(end - base)
    for va, blob in recs:
        flat[va - base:va - base + len(blob)] = blob

    segs = [
        (text_va, text, len(text), PF_R | PF_X),
        (data_va, dat, END_ADDR - data_va, PF_R | PF_W),  # memsz covers bss
    ]
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "core.bin").write_bytes(flat)
    (out_dir / "core.elf").write_bytes(make_elf(segs, entry))
    for va, blob in recs:
        print(f"record {va:#010x}-{va + len(blob):#010x} ({len(blob):#x} bytes)")
    print(f"entry {entry:#010x}, bss end {END_ADDR:#010x}")
    print(f"wrote {out_dir / 'core.bin'} and {out_dir / 'core.elf'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
