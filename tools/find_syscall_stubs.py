#!/usr/bin/env python3
"""Find the EE kernel syscall stub table in extracted/core.bin and name it.

Usage: python tools/find_syscall_stubs.py path/to/ps2sdk/ee/kernel/include/syscallnr.h

A stub is `addiu v1, zero, N; syscall; jr ra; nop`. The syscall number fixes
what the function does, so the match is by number, not by guessing. Names
come from ps2sdk's syscallnr.h (pass the path; it is not bundled here).

Prints symbol_addrs.txt lines with a status comment:
  verified     number has exactly one name in ps2sdk
  provisional  several stubs share the number, or ps2sdk calls the name
               arbitrary / reserved (RFU)
  unnamed      number not in ps2sdk: named syscall_XX
Only the contiguous stub table is named; lone stubs elsewhere are listed as
comments for later review.
"""
import re
import struct
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BASE = 0x00100000
TEXT_END = 0x00617A14
STUB_SIZE = 16


def parse_header(path: Path):
    """Return {number: [(name, note)]}, aliases resolved, in file order."""
    defs, notes = {}, {}
    for line in path.read_text().splitlines():
        m = re.match(r"#define\s+__NR_(\w+)\s+(.+?)\s*(//.*)?$", line)
        if m:
            defs[m.group(1)] = m.group(2).strip()
            notes[m.group(1)] = (m.group(3) or "").lstrip("/ ").strip()

    def value(name, seen=()):
        v = defs[name].strip("()")
        if v.startswith("__NR_"):
            return value(v[5:], seen + (name,))
        return int(v, 0)

    table = defaultdict(list)
    for name in defs:
        alias = defs[name].startswith("__NR_")
        table[value(name)].append((name, "alias" if alias else notes[name]))
    return table


def find_stubs(text: bytes):
    words = struct.unpack_from(f"<{len(text) // 4}I", text)
    for i in range(len(words) - 3):
        w = words[i]
        if w >> 16 == 0x2403 and words[i + 1] == 0x0000000C and words[i + 2] == 0x03E00008:
            n = w & 0xFFFF
            yield BASE + i * 4, n - 0x10000 if n & 0x8000 else n


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__)
        return 2
    table = parse_header(Path(sys.argv[1]))
    core = (ROOT / "extracted" / "core.bin").read_bytes()
    stubs = list(find_stubs(core[:TEXT_END - BASE]))

    # The table is the longest run of stubs spaced exactly STUB_SIZE apart.
    best, run = [], [stubs[0]]
    for prev, cur in zip(stubs, stubs[1:]):
        run = run + [cur] if cur[0] - prev[0] == STUB_SIZE else [cur]
        if len(run) > len(best):
            best = run
    in_table = {a for a, _ in best}
    count = defaultdict(int)
    for _, n in best:
        count[n] += 1

    print(f"// EE kernel syscall stubs {best[0][0]:#010x}-{best[-1][0] + STUB_SIZE:#010x}"
          f" ({len(best)} stubs). Names: ps2sdk syscallnr.h. Generated by tools/find_syscall_stubs.py")
    seen = defaultdict(int)
    for addr, n in best:
        # A name ps2sdk defines directly (not an alias) is preferred.
        names = [nm for nm, note in table.get(n, []) if note != "alias"]
        aliases = [nm for nm, note in table.get(n, []) if note == "alias"]
        k = seen[n]
        seen[n] += 1
        tag = f"{n:#x}" if n >= 0 else f"-{-n:#x}"
        if not names:
            print(f"syscall_{'m' if n < 0 else ''}{abs(n):02X} = {addr:#010x}; // type:func [unnamed] {tag} not in ps2sdk")
            continue
        if count[n] > 1:
            cands = names + aliases
            name = cands[k] if k < len(cands) else f"{cands[0]}_{k}"
            why = f"{count[n]} stubs share {tag}, order vs {', '.join(cands)} not checked"
            print(f"{name} = {addr:#010x}; // type:func [provisional] {why}")
            continue
        name = names[0]
        note = dict(table[n])[name]
        if name.startswith("RFU") and aliases:
            # ps2sdk keeps RFU as the base and the real use as an alias
            # (e.g. RFU060 -> SetupThread). Prefer the descriptive alias.
            print(f"{aliases[0]} = {addr:#010x}; // type:func [provisional] {tag}, ps2sdk says {name} alias")
        elif name.startswith("RFU") or "rbitrar" in note:
            print(f"{name} = {addr:#010x}; // type:func [provisional] {tag}, ps2sdk says {note or 'reserved'}")
        else:
            print(f"{name} = {addr:#010x}; // type:func [verified] syscall {tag}")

    lone = [(a, n) for a, n in stubs if a not in in_table]
    if lone:
        print("// Lone stubs outside the table (inside other functions, not named):")
        for a, n in lone:
            print(f"//   {a:#010x} syscall {n}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
